<#
.SYNOPSIS
  Creates or updates the flows in solution/spec/flows in dev, then activates and starts them. Idempotent.

.DESCRIPTION
  Specs are generated by tools/flowgen/build.py. Placeholders are resolved here, against dev:
    {{prompt:<name>}}  -> msdyn_aimodel ID of the published prompt
    {{tools:api}}      -> internal API name of the rfp-tools custom connector
  Each flow is a workflow row (category 5; modernflowtype 1 = agent flow, 0 = cloud flow) in the
  RFPFactory solution. Edits follow the safe cycle: deactivate, patch clientdata, activate, then stop and
  start the Power Automate runtime (skill: power-automate-skills-flow). Activation is where the platform
  validates every action, so a validation error is reported with the flow's name.

.EXAMPLE
  ./scripts/apply-flows.ps1
  ./scripts/apply-flows.ps1 -Only 'RFP - Run Pipeline'
#>
[CmdletBinding()]
param(
    [string[]]$Only,
    [switch]$Deactivate
)

. (Join-Path $PSScriptRoot 'lib\Dataverse.ps1')
$specDir = Join-Path $script:RepoRoot 'solution\spec\flows'
$url = Resolve-TargetUrl -Target dev
Connect-Dataverse -Url $url
$inSolution = @{ 'MSCRM.SolutionUniqueName' = 'RFPFactory' }

$envId = (pac env list 2>$null | Select-String ([regex]::Escape($url)) | ForEach-Object { ($_ -split '\s+') | Where-Object { $_ -match '^[0-9a-f-]{36}$' } } | Select-Object -First 1)
if (-not $envId) { throw 'Could not resolve the dev environment ID' }
$paBase = "https://api.flow.microsoft.com/providers/Microsoft.ProcessSimple/environments/$envId/flows"
function Invoke-PA([string]$Method, [string]$Path) {
    $tok = az account get-access-token --resource https://service.flow.microsoft.com/ --query accessToken -o tsv
    Invoke-RestMethod -Method $Method -Headers @{ Authorization = "Bearer $tok" } "$paBase/$Path`?api-version=2016-11-01"
}

$tools = (Invoke-Dv -Path "connectors?`$select=connectorinternalid&`$filter=name eq 'new_rfp-20factory-20tools'").value[0].connectorinternalid
if (-not $tools) { throw 'rfp-tools connector not found; run scripts/apply-connector.ps1' }
$promptIds = @{}
foreach ($m in (Invoke-Dv -Path "msdyn_aimodels?`$select=msdyn_aimodelid,msdyn_name&`$filter=startswith(msdyn_name,'RFP ')").value) { $promptIds[$m.msdyn_name] = $m.msdyn_aimodelid }

foreach ($file in Get-ChildItem $specDir -Filter '*.json' | Sort-Object Name) {
    $spec = Get-Content $file.FullName -Raw | ConvertFrom-Json -Depth 100
    if ($Only -and $spec.name -notin $Only) { continue }
    $json = $spec.clientdata | ConvertTo-Json -Depth 100 -Compress
    $json = $json.Replace('{{tools:api}}', $tools)
    foreach ($m in [regex]::Matches($json, '\{\{prompt:([^}]+)\}\}')) {
        $id = $promptIds[$m.Groups[1].Value]
        if (-not $id) { throw "$($spec.name): prompt '$($m.Groups[1].Value)' is not published; run scripts/apply-prompts.ps1" }
        $json = $json.Replace($m.Value, $id)
    }
    if ($json -match '\{\{') { throw "$($spec.name): unresolved placeholder in clientdata" }

    $existing = (Invoke-Dv -Path "workflows?`$select=workflowid,statecode,clientdata&`$filter=name eq '$($spec.name)' and category eq 5").value | Select-Object -First 1
    if ($Deactivate) {
        if ($existing) { Invoke-Dv -Method PATCH -Path "workflows($($existing.workflowid))" -Body @{ statecode = 0; statuscode = 1 } -Headers @{ 'If-Match' = '*' } | Out-Null; Write-Host "  - $($spec.name) deactivated" }
        continue
    }
    if (-not $existing) {
        $existing = Invoke-Dv -Method POST -Path 'workflows' -Headers ($inSolution + @{ Prefer = 'return=representation' }) -Body @{
            name = $spec.name; description = $spec.description; category = 5; modernflowtype = [int]$spec.modernflowtype
            type = 1; primaryentity = 'none'; statecode = 0; statuscode = 1; clientdata = $json
        }
        Write-Host "  + $($spec.name) created" -ForegroundColor Green
    } elseif ($existing.clientdata -ne $json) {
        if ($existing.statecode -eq 1) { Invoke-Dv -Method PATCH -Path "workflows($($existing.workflowid))" -Body @{ statecode = 0; statuscode = 1 } -Headers @{ 'If-Match' = '*' } | Out-Null }
        Invoke-Dv -Method PATCH -Path "workflows($($existing.workflowid))" -Body @{ clientdata = $json; description = $spec.description } -Headers @{ 'If-Match' = '*' } | Out-Null
        Write-Host "  ~ $($spec.name) updated" -ForegroundColor Yellow
    } else {
        Write-Host "  = $($spec.name)"
    }
    $id = $existing.workflowid
    $state = (Invoke-Dv -Path "workflows($id)?`$select=statecode").statecode
    if ($state -ne 1) {
        try {
            Invoke-Dv -Method PATCH -Path "workflows($id)" -Body @{ statecode = 1; statuscode = 2 } -Headers @{ 'If-Match' = '*' } | Out-Null
        } catch {
            Write-Host "  ! $($spec.name) failed to activate:" -ForegroundColor Red
            $msg = $_.ToString() -replace '\\u0027', "'" -replace '\\u0022', '"'
            Write-Host $msg.Substring(0, [Math]::Min(3000, $msg.Length))
            continue
        }
    }
    # An unchanged flow that is already on and started is left alone: a flow restarted here has been seen off a minute later.
    if ($state -eq 1 -and $existing.clientdata -eq $json -and (Invoke-PA GET $id).properties.state -eq 'Started') { continue }
    try { Invoke-PA POST "$id/stop" | Out-Null } catch {}
    try { Invoke-PA POST "$id/start" | Out-Null; $rt = (Invoke-PA GET $id).properties.state; Write-Host "    active; runtime $rt" }
    catch { Write-Host "  ! $($spec.name) runtime start failed: $($_.ErrorDetails.Message)" -ForegroundColor Red }
}
if (-not $Deactivate) {
    # Only a later read counts (ADR-0032). Report rather than restart here: activate-flows.ps1 -Target dev turns a flow back on.
    Start-Sleep -Seconds 90
    Connect-Dataverse -Url (Resolve-TargetUrl -Target dev)
    & (Join-Path $PSScriptRoot 'check-flows.ps1') -Target dev
}
